#!/usr/bin/env python3
"""Download YouTube's English auto-captions with per-word timing via the scraper.run transcript API
(free endpoint; the API key is injected by the session's network proxy) and save them as
pipeline/captions/<video_id>.json = [[start_ms, word], ...] for align.py.

Usage: python3 pipeline/fetch_captions.py VIDEO_ID [...]
"""
import json
import os
import sys
import time

import requests

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "captions")
API = "https://scraper.run/api/v1/tools/youtube/transcript"


def fetch(vid, retries=3):
    path = os.path.join(OUT, f"{vid}.json")
    if os.path.exists(path):
        return path
    body = {"url": f"https://www.youtube.com/watch?v={vid}", "language": "en",
            "fields": ["videoId", "segments", "count", "isAutoGenerated"]}
    for attempt in range(retries):
        try:
            r = requests.post(API, json=body, timeout=120)
        except requests.RequestException as e:
            err = str(e)
        else:
            if r.status_code in (200, 201):
                segs = r.json()["data"].get("segments") or []
                words = []
                for s in segs:
                    for w in s.get("words") or []:
                        t = w.get("text", "").strip()
                        if t:
                            words.append([s["startMs"] + w.get("offsetMs", 0), t])
                    if not s.get("words") and s.get("text"):  # no word timing: spread over the segment
                        ws = s["text"].split()
                        dur = max(s.get("endMs", s["startMs"]) - s["startMs"], 1)
                        words += [[s["startMs"] + int(dur * k / len(ws)), w] for k, w in enumerate(ws)]
                words.sort(key=lambda x: x[0])
                os.makedirs(OUT, exist_ok=True)
                json.dump(words, open(path, "w"), separators=(",", ":"))
                return path
            err = f"{r.status_code} {r.text[:200]}"
        time.sleep(5 * (attempt + 1))
    raise RuntimeError(f"captions for {vid} failed: {err}")


if __name__ == "__main__":
    for vid in sys.argv[1:]:
        p = fetch(vid)
        print(vid, len(json.load(open(p))), "words ->", p)
